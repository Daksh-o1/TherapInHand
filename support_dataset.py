    return {
        "en": {
            "friendly_response": _friendly_en(concern_en, impact_en),
            "symptom_explanation": explanations_en,
            "solutions": solutions_en,
            "medications": medications_en,
            "warnings": warnings_en,
            "follow_ups": _followups_en(concern_en),
        },
        "hinglish": {
            "friendly_response": _friendly_hinglish(concern_hinglish, impact_hinglish),
            "symptom_explanation": explanations_hinglish,
            "solutions": solutions_hinglish,
            "medications": medications_hinglish,
            "warnings": warnings_hinglish,
            "follow_ups": _followups_hinglish(concern_hinglish),
        },
    }


