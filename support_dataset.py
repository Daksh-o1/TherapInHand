def _sentence_case(text):
    text = (text or "").strip()
    if not text:
        return ""
    return text[0].upper() + text[1:]


def _friendly_en(concern, impact):
    impact = _sentence_case(impact)
    return [
        f"That sounds really uncomfortable. {impact}.",
        f"I'm sorry you're dealing with {concern}. {impact}.",
        f"That can feel like a lot to carry. {impact}.",
        f"I can see why {concern} would wear you down. {impact}.",
        f"You're not overreacting here. {impact}.",
    ]


def _friendly_hinglish(concern, impact):
    impact = _sentence_case(impact)
    return [
        f"Ye kaafi tough lag raha hai. {impact}.",
        f"Mujhe afsos hai ki tum {concern} se deal kar rahe ho. {impact}.",
        f"Ye sach me heavy feel ho sakta hai. {impact}.",
        f"Samajh sakta hoon ki {concern} kitna draining ho sakta hai. {impact}.",
        f"Tum overreact nahi kar rahe. {impact}.",
    ]


